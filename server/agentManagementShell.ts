/*
  Agent 管理流量代理 + fwxm 管理命令（上游 v2.3.284 的 agent-proxy.sh / forwardx-manage.sh 移植）。

  - 安装 / 升级脚本认 --proxy URL / --no-proxy（或环境变量 FORWARDX_AGENT_PROXY），写进
    config.json 的 proxyUrl；Agent 2.2.229 起和面板之间的管理流量走它（agent/management_proxy.go），
    安装脚本自己的下载也走它。业务转发和探测不走。
  - 不指定时升级沿用 config.json 里已有的 proxyUrl；什么都没配就和原来一样（跟随环境变量）。
  - 装完放一个 /usr/local/bin/fwxm：SSH 上看状态、看日志、重启、改代理、升级 / 修复 / 卸载 Agent。

  代理密码不打印、不进命令行参数（curl 走环境变量，Agent 读只有 root 能读的配置文件）。

  这里的 bash 都是 JS 字符串数组拼出来的（和 agentInstallScripts.ts 同一种写法），不在运行时
  读 scripts/ 下的文件：Docker 镜像和本机部署都不一定带着源码目录。
*/

/** 从这个 Agent 版本起认 config.json 里的 proxyUrl（agent/management_proxy.go 里是同一个数）。 */
export const AGENT_MANAGEMENT_PROXY_VERSION = "2.2.229";

export const FWXM_PATH = "/usr/local/bin/fwxm";
export const AGENT_MANAGE_DIR = "/etc/forwardx/manage";

/** 安装脚本和 fwxm 共用的 bash 函数。依赖 CONFIG_DIR / LEGACY_CONFIG_DIR / GO_AGENT_BIN 三个变量。 */
export function agentProxyShellFunctions(): string[] {
  return [
    '# ---- 管理流量代理（server/agentManagementShell.ts）----',
    `FWX_AGENT_PROXY_MIN_VERSION="${AGENT_MANAGEMENT_PROXY_VERSION}"`,
    'fwx_proxy_normalize() {',
    '  local value="$1" authority endpoint port',
    '  [ -z "$value" ] && return 0',
    '  # direct：明确要求直连，连系统环境变量里的代理也不用（和「没设置」不同，没设置是跟随环境变量）。',
    '  [ "$value" = direct ] && { printf "direct"; return 0; }',
    '  case "$value" in http://*|https://*|socks5://*|socks5h://*) ;; *) echo "[错误] 代理只支持 http://、https://、socks5://、socks5h://" >&2; return 1 ;; esac',
    '  case "$value" in *[[:space:]]*|*"?"*|*"#"*) echo "[错误] 代理地址格式不对；账号密码里的特殊字符请先做 URL 编码" >&2; return 1 ;; esac',
    '  authority="${value#*://}"',
    '  authority="${authority%/}"',
    '  case "$authority" in */*|"") echo "[错误] 代理地址只能是 协议://主机:端口，不能带路径" >&2; return 1 ;; esac',
    '  endpoint="${authority##*@}"',
    '  port="${endpoint##*:}"',
    '  case "$port" in ""|*[!0-9]*) echo "[错误] 代理地址缺少端口" >&2; return 1 ;; esac',
    '  if [ "${#port}" -gt 5 ] || [ "$port" -lt 1 ] || [ "$port" -gt 65535 ] || [ "$endpoint" = "$port" ] || [ -z "${endpoint%:*}" ]; then',
    '    echo "[错误] 代理地址要有主机名和 1-65535 之间的端口" >&2; return 1',
    '  fi',
    '  value="${value%/}"',
    '  case "$value" in socks5://*) value="socks5h://${value#socks5://}" ;; esac',
    '  printf "%s" "$value"',
    '}',
    '',
    '# 只打印协议和 主机:端口，账号密码换成 ***。',
    'fwx_proxy_redacted() {',
    '  local value="$1" scheme authority',
    '  [ -n "$value" ] || { echo "未设置代理（跟随系统环境变量，一般就是直连）"; return 0; }',
    '  [ "$value" = direct ] && { echo "直连（不走任何代理，包括系统环境变量里的）"; return 0; }',
    '  scheme="${value%%://*}"; authority="${value#*://}"',
    '  case "$authority" in *@*) printf "%s://***@%s\\n" "$scheme" "${authority##*@}" ;; *) printf "%s\\n" "$value" ;; esac',
    '}',
    '',
    '# 让这个 shell 里的 curl / apt / dnf 都走代理。没配代理时不动现有环境变量（和原来一样）。',
    'fwx_proxy_environment() {',
    '  local value="$1"',
    '  [ -n "$value" ] || return 0',
    '  unset http_proxy https_proxy all_proxy HTTP_PROXY HTTPS_PROXY ALL_PROXY no_proxy NO_PROXY',
    '  [ "$value" = direct ] && return 0',
    '  export http_proxy="$value" https_proxy="$value" all_proxy="$value"',
    '  export HTTP_PROXY="$value" HTTPS_PROXY="$value" ALL_PROXY="$value" no_proxy="" NO_PROXY=""',
    '}',
    '',
    'fwx_config_file() {',
    '  if [ -f "$CONFIG_DIR/config.json" ]; then echo "$CONFIG_DIR/config.json"',
    '  elif [ -f "$LEGACY_CONFIG_DIR/config.json" ]; then echo "$LEGACY_CONFIG_DIR/config.json"',
    '  fi',
    '}',
    '',
    '# 现有配置里的 proxyUrl（没有这个字段就是空）。配置坏了返回 1：不能悄悄当成直连。',
    'fwx_config_proxy() {',
    '  local file',
    '  file="$(fwx_config_file)"',
    '  [ -n "$file" ] || return 0',
    '  grep -q "\\"proxyUrl\\"" "$file" 2>/dev/null || return 0',
    '  command -v jq >/dev/null 2>&1 || { echo "[错误] 需要 jq 才能安全读取现有的代理设置" >&2; return 1; }',
    '  jq -er \'if type == "object" and (.proxyUrl == null or (.proxyUrl | type == "string")) then (.proxyUrl // "") else error("invalid proxy config") end\' "$file" 2>/dev/null || { echo "[错误] Agent 配置里的 proxyUrl 无效" >&2; return 1; }',
    '}',
    '',
    '# 解析 install / upgrade / uninstall、TOKEN 和 --proxy URL / --no-proxy。',
    'fwx_agent_proxy_args() {',
    '  ACTION="" TOKEN=""',
    '  FWX_PROXY_EXPLICIT=false',
    '  if [ "${FORWARDX_AGENT_PROXY+x}" = x ]; then FWX_PROXY_EXPLICIT=true; fi',
    '  while [ "$#" -gt 0 ]; do',
    '    case "$1" in',
    '      install|upgrade|update|uninstall|remove|delete)',
    '        [ -z "$ACTION" ] || { echo "[错误] 只能指定一个操作" >&2; return 1; }',
    '        ACTION="$1"; shift ;;',
    '      --proxy)',
    '        [ "$#" -ge 2 ] && [ -n "$2" ] || { echo "[错误] --proxy 后面要跟代理地址" >&2; return 1; }',
    '        FORWARDX_AGENT_PROXY="$2"; FWX_PROXY_EXPLICIT=true; shift 2 ;;',
    '      --proxy=*) FORWARDX_AGENT_PROXY="${1#*=}"; FWX_PROXY_EXPLICIT=true; shift ;;',
    '      --no-proxy) FORWARDX_AGENT_PROXY=direct; FWX_PROXY_EXPLICIT=true; shift ;;',
    '      -h|--help|help) ACTION=help; shift ;;',
    '      --*) echo "[错误] 不认识的参数: ${1%%=*}" >&2; return 1 ;;',
    '      *) [ -z "$TOKEN" ] || { echo "[错误] 多余的参数" >&2; return 1; }; TOKEN="$1"; shift ;;',
    '    esac',
    '  done',
    '  # 卸载和帮助在配置坏掉、没装 jq 的机器上也要能用。',
    '  case "$ACTION" in uninstall|remove|delete|help|"") return 0 ;; esac',
    '  if [ "$FWX_PROXY_EXPLICIT" != true ]; then',
    '    FORWARDX_AGENT_PROXY="$(fwx_config_proxy)" || return 1',
    '  elif [ -z "${FORWARDX_AGENT_PROXY:-}" ]; then',
    '    FORWARDX_AGENT_PROXY=direct',
    '  fi',
    '  FORWARDX_AGENT_PROXY="$(fwx_proxy_normalize "${FORWARDX_AGENT_PROXY:-}")" || return 1',
    '  export FORWARDX_AGENT_PROXY',
    '  fwx_proxy_environment "$FORWARDX_AGENT_PROXY"',
    '  if [ -n "$FORWARDX_AGENT_PROXY" ]; then echo "[信息] 管理流量: $(fwx_proxy_redacted "$FORWARDX_AGENT_PROXY")（只管和面板的通信与下载，不影响转发）"; fi',
    '}',
    '',
    '# 把 FORWARDX_AGENT_PROXY 写进 config.json（保留其它字段，原子替换，600 权限）。',
    'fwx_agent_proxy_save() {',
    '  local file="$CONFIG_DIR/config.json" tmp',
    '  [ -f "$file" ] || return 0',
    '  tmp="$(mktemp "$CONFIG_DIR/.proxy-config.XXXXXX")" || return 1',
    '  if jq --arg proxy "${FORWARDX_AGENT_PROXY:-}" \'if type == "object" then (if $proxy == "" then del(.proxyUrl) else .proxyUrl = $proxy end) else error("invalid config") end\' "$file" > "$tmp" && chmod 600 "$tmp" && mv -f "$tmp" "$file"; then return 0; fi',
    '  rm -f "$tmp"',
    '  echo "[错误] 无法保存 Agent 代理设置" >&2',
    '  return 1',
    '}',
    '',
    '# a >= b（点分版本号）。',
    'fwx_version_ge() {',
    '  [ "$(printf "%s\\n%s\\n" "$1" "$2" | sort -V | head -n 1)" = "$2" ]',
    '}',
    '',
    '# 已装的 Agent 认不认 proxyUrl。老版本没有 -version 参数，会报错退出。',
    'fwx_agent_supports_proxy() {',
    '  local version',
    '  version="$("$GO_AGENT_BIN" -version 2>/dev/null | head -n 1 | tr -d " \\t\\n\\r")" || version=""',
    '  [ -n "$version" ] && fwx_version_ge "$version" "$FWX_AGENT_PROXY_MIN_VERSION"',
    '}',
    '',
    'fwx_warn_if_proxy_unsupported() {',
    '  [ -n "${FORWARDX_AGENT_PROXY:-}" ] || return 0',
    '  [ -x "$GO_AGENT_BIN" ] || return 0',
    '  if ! fwx_agent_supports_proxy; then',
    '    echo "[警告] 当前 Agent 版本不支持管理代理（需要 Agent ${FWX_AGENT_PROXY_MIN_VERSION} 及以上）：下载已经走代理，但 Agent 和面板之间仍是直连。升级面板和 Agent 后自动生效。"',
    '  fi',
    '}',
  ];
}

/** /usr/local/bin/fwxm 的内容（只管 Agent；面板那一侧的管理菜单 NEX 不在这里做）。 */
export function fwxmScript(): string {
  return [
    '#!/bin/bash',
    '# fwxm —— NEX Agent 的 SSH 管理命令（由 Agent 安装 / 升级脚本写入，server/agentManagementShell.ts 生成）。',
    'set -uo pipefail',
    'CONFIG_DIR="${FORWARDX_AGENT_CONFIG_DIR:-/etc/forwardx/agent}"',
    'LEGACY_CONFIG_DIR="/etc/forwardx-agent"',
    'GO_AGENT_BIN="${FWXM_AGENT_BIN:-/usr/local/bin/forwardx-agent}"',
    'SERVICE_NAME="forwardx-agent"',
    'LOG_FILE="/var/log/forwardx-agent/agent-go.log"',
    `MANAGE_DIR="\${FWXM_MANAGE_DIR:-${AGENT_MANAGE_DIR}}"`,
    '',
    'die() { echo "[错误] $*" >&2; exit 1; }',
    'usage() {',
    '  cat <<"HELP"',
    'NEX Agent 管理命令 fwxm',
    '  fwxm                     交互菜单',
    '  fwxm info                面板地址、配置文件、代理、服务名',
    '  fwxm status              服务状态',
    '  fwxm logs                跟踪 Agent 日志（Ctrl+C 退出）',
    '  fwxm start|stop|restart  启停 Agent 服务（转发进程由各自的服务管理，不受影响）',
    '  fwxm proxy show          查看管理流量代理（密码打码）',
    '  fwxm proxy set [URL]     设置代理：http://、https://、socks5://、socks5h://（省略 URL 时隐藏输入）',
    '  fwxm proxy off           改回直连',
    '  fwxm upgrade             从面板拉安装脚本升级 Agent（沿用现有配置和代理）',
    '  fwxm repair              保留配置，重装二进制并重启（等同 upgrade）',
    '  fwxm uninstall           卸载 Agent（会中断这台机器上的转发）',
    '  fwxm version             Agent 版本',
    '代理只管 Agent 和面板之间的通信、安装 / 升级时的下载；业务转发和延迟探测不走代理。',
    'HELP',
    '}',
    '',
    'case "${1:-}" in -h|--help|help) usage; exit 0 ;; esac',
    '[ "$(id -u)" = 0 ] || die "请用 root（sudo fwxm）运行"',
    '[ -r "$MANAGE_DIR/agent-proxy.sh" ] || die "管理组件缺失，请重新运行一次 Agent 安装 / 升级脚本"',
    '# 安装脚本写入的 root 专属文件（600），不是用户配置。',
    '# shellcheck source=/dev/null',
    'source "$MANAGE_DIR/agent-proxy.sh"',
    '',
    'CONFIG_FILE="$(fwx_config_file)"',
    'config_value() {',
    '  [ -n "$CONFIG_FILE" ] || return 0',
    '  command -v jq >/dev/null 2>&1 || die "需要 jq 才能读取 Agent 配置"',
    '  jq -r --arg key "$1" \'if type == "object" then (.[$key] // "") else error("invalid config") end\' "$CONFIG_FILE" 2>/dev/null || die "Agent 配置无法读取"',
    '}',
    'confirm() {',
    '  local answer',
    '  [ -r /dev/tty ] && [ -w /dev/tty ] || die "这个操作需要在交互式 SSH 终端里确认"',
    '  printf "%s [y/N] " "$1" > /dev/tty',
    '  IFS= read -r answer < /dev/tty || return 1',
    '  case "$answer" in y|Y|yes|YES) return 0 ;; *) return 1 ;; esac',
    '}',
    'service_action() {',
    '  local action="$1"',
    '  if command -v systemctl >/dev/null 2>&1 && [ -d /run/systemd/system ]; then',
    '    if [ "$action" = status ]; then systemctl status "$SERVICE_NAME" --no-pager -l; else systemctl "$action" "$SERVICE_NAME"; fi',
    '  elif command -v rc-service >/dev/null 2>&1; then rc-service "$SERVICE_NAME" "$action"',
    '  elif [ -x "/etc/init.d/$SERVICE_NAME" ]; then "/etc/init.d/$SERVICE_NAME" "$action"',
    '  else die "找不到可用的服务管理器"; fi',
    '}',
    'agent_version() { "$GO_AGENT_BIN" -version 2>/dev/null | head -n 1 || true; }',
    '',
    'proxy_cmd() {',
    '  local action="${1:-show}" value="" tmp',
    '  [ -n "$CONFIG_FILE" ] || die "没找到 Agent 配置，先安装 Agent"',
    '  case "$action" in',
    '    show) fwx_proxy_redacted "$(fwx_config_proxy)"; return 0 ;;',
    '    off|remove|delete|direct) value=direct ;;',
    '    set|add)',
    '      value="${2:-}"',
    '      if [ -z "$value" ]; then',
    '        [ -r /dev/tty ] || die "请在命令里给出代理地址：fwxm proxy set URL"',
    '        printf "代理地址（输入不回显）: " > /dev/tty',
    '        IFS= read -rs value < /dev/tty; printf "\\n" > /dev/tty',
    '      fi',
    '      [ -n "$value" ] || die "代理地址为空；改回直连请用 fwxm proxy off"',
    '      value="$(fwx_proxy_normalize "$value")" || exit 1 ;;',
    '    *) die "用法: fwxm proxy show|set [URL]|off" ;;',
    '  esac',
    '  CONFIG_DIR="$(dirname "$CONFIG_FILE")"',
    '  FORWARDX_AGENT_PROXY="$value"',
    '  fwx_agent_proxy_save || die "代理设置没有保存，Agent 未重启"',
    '  echo "[完成] 已保存：$(fwx_proxy_redacted "$value")。重启 Agent 生效（只重启 Agent，转发不中断）。"',
    '  fwx_warn_if_proxy_unsupported',
    '  service_action restart',
    '}',
    '',
    '# 从面板拉安装脚本执行（和面板上给的 curl | bash 是同一个脚本），下载走现有代理。',
    'run_installer() {',
    '  local mode="$1" panel tmp proxy',
    '  panel="$(config_value panelUrl)"; panel="${panel%/}"',
    '  [ -n "$panel" ] || die "Agent 配置里没有面板地址"',
    '  proxy="$(fwx_config_proxy)" || exit 1',
    '  fwx_proxy_environment "$proxy"',
    '  tmp="$(mktemp /tmp/nex-agent-install.XXXXXX)" || die "无法创建临时文件"',
    '  trap \'rm -f "$tmp"\' EXIT',
    '  echo "[信息] 从面板获取安装脚本: $panel"',
    '  curl -fsSL --connect-timeout 15 --speed-limit 1024 --speed-time 60 "$panel/api/agent/install.sh" -o "$tmp" || die "下载安装脚本失败（面板不可达时可改用 GitHub 上的 install-agent.sh）"',
    '  bash -n "$tmp" || die "安装脚本校验失败，已取消"',
    '  PANEL_URL="$panel" bash "$tmp" "$mode"',
    '}',
    '',
    'ACTION="${1:-}"; [ "$#" = 0 ] || shift',
    '[ "$ACTION" = agent ] && { ACTION="${1:-}"; [ "$#" = 0 ] || shift; }',
    'if [ -z "$ACTION" ]; then',
    '  [ -r /dev/tty ] || { usage; exit 0; }',
    '  printf "\\nNEX Agent 管理\\n" > /dev/tty',
    '  printf "%s\\n" "  1) 关键信息" "  2) 运行状态" "  3) 查看日志" "  4) 重启 Agent" "  5) 代理设置" "  6) 升级" "  7) 重装修复" "  8) 卸载" "  0) 退出" > /dev/tty',
    '  printf "选择: " > /dev/tty; IFS= read -r choice < /dev/tty || exit 0',
    '  case "$choice" in',
    '    1) ACTION=info ;; 2) ACTION=status ;; 3) ACTION=logs ;; 4) ACTION=restart ;;',
    '    5) printf "代理: 1) 查看  2) 设置  3) 改回直连: " > /dev/tty; IFS= read -r choice < /dev/tty || exit 0; ACTION=proxy',
    '       case "$choice" in 1) set -- show ;; 2) set -- set ;; 3) set -- off ;; *) exit 0 ;; esac ;;',
    '    6) ACTION=upgrade ;; 7) ACTION=repair ;; 8) ACTION=uninstall ;; *) exit 0 ;;',
    '  esac',
    'fi',
    '',
    'case "$ACTION" in',
    '  info|config|address)',
    '    echo "面板地址:  $(config_value panelUrl)"',
    '    echo "配置文件:  ${CONFIG_FILE:-（未安装）}"',
    '    printf "管理代理:  "; fwx_proxy_redacted "$(fwx_config_proxy)"',
    '    echo "Agent:     $(agent_version || true)"',
    '    echo "服务名称:  $SERVICE_NAME"',
    '    echo "日志文件:  $LOG_FILE"',
    '    echo "手工改了配置文件后要重启 Agent：fwxm restart" ;;',
    '  status|start|stop|restart) service_action "$ACTION" ;;',
    '  logs) tail -n 100 -F "$LOG_FILE" ;;',
    '  proxy) proxy_cmd "$@" ;;',
    '  version) agent_version ;;',
    '  upgrade|update) run_installer upgrade ;;',
    '  repair) confirm "保留配置，重装 Agent 二进制并重启？" || exit 0; run_installer upgrade ;;',
    '  uninstall|remove) confirm "卸载 Agent 会停掉这台机器上由面板管理的转发，继续？" || exit 0; run_installer uninstall ;;',
    '  *) usage; exit 1 ;;',
    'esac',
  ].join('\n') + '\n';
}

/** 安装 / 升级时写入 fwxm 和它用的函数文件（heredoc 用带引号的定界符，内容原样落盘）。 */
export function installManagementCommandFunction(): string[] {
  return [
    'install_management_command() {',
    `  local dir="${AGENT_MANAGE_DIR}"`,
    '  mkdir -p "$dir" /usr/local/bin || return 0',
    '  chmod 700 "$dir" 2>/dev/null || true',
    "  cat > \"$dir/agent-proxy.sh.new\" <<'FWX_AGENT_PROXY_ASSET'",
    ...agentProxyShellFunctions(),
    'FWX_AGENT_PROXY_ASSET',
    "  cat > \"$dir/fwxm.new\" <<'FWX_MANAGE_ASSET'",
    fwxmScript().trimEnd(),
    'FWX_MANAGE_ASSET',
    '  if bash -n "$dir/agent-proxy.sh.new" && bash -n "$dir/fwxm.new"; then',
    '    chmod 600 "$dir/agent-proxy.sh.new" && mv -f "$dir/agent-proxy.sh.new" "$dir/agent-proxy.sh"',
    `    install -m 755 "$dir/fwxm.new" "${FWXM_PATH}.new" && mv -f "${FWXM_PATH}.new" "${FWXM_PATH}"`,
    '    rm -f "$dir/fwxm.new"',
    // OpenWrt 的 PATH 里没有 /usr/local/bin：链一份到 /usr/bin，登录上去直接敲 fwxm。
    `    if [ -f /etc/openwrt_release ]; then ln -sf "${FWXM_PATH}" /usr/bin/fwxm 2>/dev/null || true; fi`,
    '    echo "[信息] SSH 管理命令: fwxm（查看状态、日志、代理设置、升级）"',
    '  else',
    '    rm -f "$dir/agent-proxy.sh.new" "$dir/fwxm.new"',
    '    echo "[警告] 管理命令 fwxm 校验失败，未更新"',
    '  fi',
    '}',
  ];
}
