    '  tuning_last() { echo "$1" | awk \'{print $NF}\'; }',
    '  tuning_numeric() { case "$1" in ""|*[!0-9]*) return 1 ;; esac; return 0; }',
    '  # 把最后一个字段抬到至少 $2（tcp_rmem 这类三元组只动上限）',
    '  tuning_raise() {',
    '    cur=$(tuning_current "$1"); last=$(tuning_last "$cur")',
    '    tuning_numeric "$last" || return 0',
    '    if [ "$last" -ge "$2" ]; then echo "$1 = $cur" >> "$TUNING_TMP"; return 0; fi',
    '    echo "$1 = $(echo "$cur" | awk -v m="$2" \'{$NF=m; print}\')" >> "$TUNING_TMP"',
    '  }',
    '  # 把值压到至多 $2',
    '  tuning_lower() {',
    '    cur=$(tuning_current "$1")',
    '    tuning_numeric "$cur" || return 0',
    '    if [ "$cur" -le "$2" ]; then echo "$1 = $cur" >> "$TUNING_TMP"; else echo "$1 = $2" >> "$TUNING_TMP"; fi',
    '  }',
    '  # 大缓冲：长距离线路的带宽时延积需要，UDP 监听缓冲也受 rmem_max 限制。',
