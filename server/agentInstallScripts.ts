    "        echo \"[信息] gost runtime 已从现有 gost 复制: $RUNTIME_BIN\"",
    "        return 0",
    "      fi",
    "      rm -f \"$STAGED_RUNTIME\"",
    "    fi",
    "  done",
    "  if command -v gost >/dev/null 2>&1; then",
    "    echo \"[警告] 已安装的 gost 与当前 CPU 不兼容或版本不匹配，正在重新安装\"",
    "  fi",
    "  if is_enabled_value \"${FORWARDX_AGENT_PANEL_FIRST:-}\"; then",
    "    if install_runtime_from_panel; then",
    "      return 0",
    "    fi",
    "    echo \"[信息] 面板 gost runtime 不可用，尝试从 GitHub 安装...\"",
    "    if install_runtime_from_github; then",
    "      return 0",
    "    fi",
    "  else",
    "    if install_runtime_from_github; then",
    "      return 0",
    "    fi",
    "    echo \"[信息] GitHub gost runtime 下载失败，回退到面板安装...\"",
    "    if install_runtime_from_panel; then",
    "      return 0",
    "    fi",
    "  fi",
    "  echo \"[警告] gost 安装失败，gost 转发方式将不可用\"",
    "  return 1",
    "}",
    "",
    'install_go_agent() {',
    '  GO_ARCH=$(detect_arch)',
    '  if [ -z "$GO_ARCH" ]; then',
    '    echo "[错误] 不支持的 CPU 架构: $(uname -m)"',
    '    return 1',
    '  fi',
    '',
    '  echo "[步骤 3/6] 安装 Go Agent（Release v${RELEASE_VERSION}）..."',
