    '  return 0',
    '}',
    '',
    'register_agent_once() {',
    '  echo "[步骤 6/6] 注册到面板..."',
    '  local OUT RC',
    '  if OUT=$("$GO_AGENT_BIN" -config "$CONFIG_DIR/config.json" -register 2>&1); then',
    '    [ -n "$OUT" ] && printf "%s\\n" "$OUT"',
    '    echo "[信息] Agent 已通过加密通道注册到面板"',
    '    return 0',
    '  else',
    '    RC=$?',
    '    echo "[错误] Agent 注册失败（退出码: ${RC}）"',
    '    [ -n "$OUT" ] && printf "%s\\n" "$OUT"',
    '    echo "[提示] 请检查 Token 是否来自当前面板、面板地址/反代是否指向当前实例，以及服务器时间是否正常"',
    '    return "$RC"',
    '  fi',
    '}',
    '',
    'start_agent_service_systemd_unused() {',
    '  if ! systemctl restart "$SERVICE_NAME"; then',
    '    echo "[错误] systemd 服务启动失败"',
    '    systemctl status "$SERVICE_NAME" --no-pager -l 2>/dev/null || true',
    '    return 1',
    '  fi',
    '  sleep 1',
    '  if ! systemctl is-active --quiet "$SERVICE_NAME"; then',
    '    echo "[错误] systemd 服务未保持运行"',
    '    systemctl status "$SERVICE_NAME" --no-pager -l 2>/dev/null || true',
    '    journalctl -u "$SERVICE_NAME" -n 50 --no-pager 2>/dev/null || true',
    '    return 1',
    '  fi',
    '  echo "[信息] systemd 服务已启动"',
    '}',
