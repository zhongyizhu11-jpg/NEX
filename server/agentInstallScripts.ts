    '  if ! install_go_agent; then',
    '    echo "[错误] Go Agent 安装失败，安装中止"',
    '    exit 1',
    '  fi',
    '',
    '  # 安装可选转发工具',
    '  install_realm || true',
    '  if is_enabled_value "${FORWARDX_INSTALL_NGINX:-}"; then',
    '    install_nginx_runtime || true',
